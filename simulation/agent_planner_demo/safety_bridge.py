"""C23 ABI safety gate bridge into libaegis_spark.

Streams untrusted AI kinematic commands across the C23 boundary to the Gold-proved
SPARK safety supervisor, verifying that safe commands pass through while unsafe
commands are clamped strictly to 0.0 Nm in State_Fault_Estop.
"""

import math
from dataclasses import dataclass
from typing import TYPE_CHECKING


if TYPE_CHECKING:
    from simulation.agent_planner_demo.trajectory import TrajectoryCommand
from tests.python.aegis_ffi import HALOS_DOF_COUNT
from tests.python.aegis_ffi import HALOS_HSM_RESET_MAGIC
from tests.python.aegis_ffi import HalosComposedGate
from tests.python.aegis_ffi import HalosFaultCode
from tests.python.aegis_ffi import HalosHsmEvent
from tests.python.aegis_ffi import HalosHsmState
from tests.python.aegis_ffi import HalosHsmStatus
from tests.python.aegis_ffi import HalosKinematicCmd
from tests.python.aegis_ffi import HalosWatchdogState
from tests.python.aegis_ffi import composed_gate_create
from tests.python.aegis_ffi import composed_gate_intercept
from tests.python.aegis_ffi import hsm_process_event
from tests.python.aegis_ffi import hsm_reset


@dataclass
class SafetyInterceptionResult:
    """Interception telemetry and clamping verification result."""

    step: int
    timestamp_ns: int
    is_safe: bool
    commanded_torque_nm: list[float]
    safe_torque_nm: list[float]
    commanded_velocity_rad: list[float]
    safe_velocity_rad: list[float]
    hsm_state: HalosHsmState
    last_fault_code: HalosFaultCode
    status: HalosHsmStatus
    description: str


class SafetyBridge:
    """C23 ABI bridge to the SPARK Ada composed safety gate."""

    def __init__(self, start_ns: int = 1_000_000) -> None:
        """Initialize the composed safety gate and transition to Active state.

        Args:
            start_ns: Simulation epoch start timestamp in nanoseconds.
        """
        self._gate: HalosComposedGate = composed_gate_create(start_ns)
        self._arm_and_activate()

    def _arm_and_activate(self) -> None:
        """Execute built-in self-test transition from State_Boot to State_Active."""
        hsm_process_event(
            self._gate.hsm,
            HalosHsmEvent.HALOS_EVENT_SELF_TEST_PASSED,
            HalosFaultCode.HALOS_FAULT_NONE,
        )
        self._gate.kinematics.hsm = self._gate.hsm

    @property
    def hsm_state(self) -> HalosHsmState:
        """Current hierarchical safety state machine state."""
        return HalosHsmState(self._gate.hsm.state)

    @property
    def watchdog_state(self) -> HalosWatchdogState:
        """Current watchdog supervision device state."""
        return HalosWatchdogState(self._gate.watchdog.state)

    @property
    def last_fault_code(self) -> HalosFaultCode:
        """Last recorded fault code."""
        return HalosFaultCode(self._gate.hsm.last_fault_code)

    @property
    def transition_count(self) -> int:
        """Monotonic count of state machine transitions."""
        return int(self._gate.hsm.transition_count)

    def intercept(self, cmd: TrajectoryCommand) -> SafetyInterceptionResult:
        """Stream joint trajectory command across C23 ABI into SPARK safety gate.

        Args:
            cmd: Command packet generated by the AI trajectory planner.

        Returns:
            SafetyInterceptionResult containing safe clamped outputs and safety state.

        Raises:
            RuntimeError: If safety invariant 1 is violated during a fault state.
        """
        kcmd = HalosKinematicCmd()
        kcmd.timestamp_ns = cmd.timestamp_ns

        for i in range(HALOS_DOF_COUNT):
            kcmd.position_rad[i] = cmd.position_rad[i]
            kcmd.velocity_rad[i] = cmd.velocity_rad[i]
            kcmd.torque_nm[i] = cmd.torque_nm[i]

        safe_tau, safe_vel, status = composed_gate_intercept(
            self._gate,
            kcmd,
            cmd.timestamp_ns,
        )

        is_safe = status == HalosHsmStatus.HALOS_HSM_OK
        curr_state = self.hsm_state
        curr_fault = self.last_fault_code

        # Safety Invariant 1 Verification: If unsafe, torque and velocity MUST be exactly 0.0 Nm
        if not is_safe:
            for val in safe_tau:
                if not math.isclose(val, 0.0, abs_tol=1e-7):
                    err_msg = f'Safety Invariant 1 violation: non-zero torque {val} during fault'
                    raise RuntimeError(err_msg)
            for val in safe_vel:
                if not math.isclose(val, 0.0, abs_tol=1e-7):
                    err_msg = f'Safety Invariant 1 violation: non-zero velocity {val} during fault'
                    raise RuntimeError(err_msg)

        desc = (
            'Nominal pass-through verified' if is_safe else f'Fault intercepted & clamped to 0.0 Nm ({curr_fault.name})'
        )

        return SafetyInterceptionResult(
            step=cmd.step,
            timestamp_ns=cmd.timestamp_ns,
            is_safe=is_safe,
            commanded_torque_nm=list(cmd.torque_nm),
            safe_torque_nm=safe_tau,
            commanded_velocity_rad=list(cmd.velocity_rad),
            safe_velocity_rad=safe_vel,
            hsm_state=curr_state,
            last_fault_code=curr_fault,
            status=status,
            description=desc,
        )

    def reset_fault(
        self,
        resume_timestamp_ns: int,
        reset_key: int = HALOS_HSM_RESET_MAGIC,
    ) -> bool:
        """Perform authorized safety supervisor reset from Fault_Estop back to Active.

        Args:
            resume_timestamp_ns: New baseline monotonic timestamp after recovery.
            reset_key: 32-bit authorization token (defaults to HALOS_HSM_RESET_MAGIC).

        Returns:
            True if safety gate successfully re-entered Active state, False if reset rejected.
        """
        # 1. Reset HSM with key and verify status code from SPARK
        status = hsm_reset(self._gate.hsm, reset_key)
        if status != HalosHsmStatus.HALOS_HSM_OK:
            return False

        # 2. Re-initialize watchdog device to armed state at resume timestamp
        self._gate = composed_gate_create(resume_timestamp_ns)

        # 3. Transition HSM from State_Boot to State_Active
        self._arm_and_activate()
        return self.hsm_state == HalosHsmState.HALOS_HSM_ACTIVE
